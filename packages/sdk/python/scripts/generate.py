"""Regenerates src/kyora/{_models,_error_codes,_operations}.py from packages/sdk/typescript/openapi.yaml.

`--check` regenerates into a temporary directory and fails when the checked-in files differ.
"""

import argparse
import difflib
import re
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT.parent / "typescript" / "openapi.yaml"
PACKAGE = ROOT / "src" / "kyora"
HEADER = "# Generated by scripts/generate.py from packages/sdk/typescript/openapi.yaml. Do not edit.\n"

CODEGEN_ARGS = [
    "--input-file-type", "openapi",
    "--output-model-type", "pydantic_v2.BaseModel",
    "--target-python-version", "3.10",
    "--snake-case-field",
    "--allow-population-by-field-name",
    "--use-annotated",
    "--use-union-operator",
    "--use-standard-collections",
    "--field-constraints",
    "--enum-field-as-literal", "all",
    "--use-schema-description",
    "--disable-timestamp",
    "--formatters", "builtin",
]  # fmt: skip

STRING_LITERAL = re.compile(r"Literal\[('[^'\]]*'(?:, '[^'\]]*')*)\]")


def models(spec: Path) -> str:
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "models.py"
        subprocess.run(["datamodel-codegen", "--input", str(spec), "--output", str(out), *CODEGEN_ARGS], check=True)
        text = out.read_text()
    # /v1 adds enum values without notice: an unknown one must still parse
    text = STRING_LITERAL.sub(r"Literal[\1] | str", text)
    return HEADER + text.split("\n", 1)[1] if text.startswith("#") else HEADER + text


def error_codes(spec: Path) -> str:
    document = yaml.safe_load(spec.read_text())
    catalog = document["x-kyora-error-codes"]
    lines = [
        HEADER,
        f"SPEC_VERSION = {document['info']['version']!r}\n\n",
        "from typing import Literal, TypedDict\n\n",
        "ErrorClass = Literal['auth', 'conflict', 'invalid', 'limit', 'not_found', 'transient', 'unavailable']\n\n\n",
        "class ErrorCode(TypedDict):\n",
        "    status: tuple[int, ...]\n",
        "    retryable: bool | tuple[int, ...]\n",
        "    error_class: ErrorClass\n",
        "    description: str\n\n\n",
        "ERROR_CODES: dict[str, ErrorCode] = {\n",
    ]
    for code in sorted(catalog):
        entry = catalog[code]
        status = tuple(entry["status"])
        retryable = entry["retryable"] if isinstance(entry["retryable"], bool) else tuple(entry["retryable"])
        lines.append(
            f"    {code!r}: {{'status': {status!r}, 'retryable': {retryable!r}, "
            f"'error_class': {entry['class']!r}, 'description': {entry['description']!r}}},\n"
        )
    lines.append("}\n")
    return "".join(lines)


def operations(spec: Path) -> str:
    document = yaml.safe_load(spec.read_text())
    shared = document["components"].get("parameters", {})

    def resolve(parameter: dict) -> dict:
        return shared[parameter["$ref"].rsplit("/", 1)[1]] if "$ref" in parameter else parameter

    lines = [
        HEADER,
        "from typing import Literal, TypedDict\n\n\n",
        "class Operation(TypedDict):\n",
        "    method: str\n",
        "    path: str\n",
        "    tag: str\n",
        "    path_params: tuple[str, ...]\n",
        "    query: tuple[str, ...]\n",
        "    idempotency_key: bool\n",
        "    body: Literal['none', 'json', 'binary']\n",
        "    body_required: bool\n",
        "    content_types: tuple[str, ...]\n",
        "    response: Literal['json', 'ndjson', 'binary', 'none', 'websocket']\n",
        "    statuses: tuple[int, ...]\n\n\n",
        "OPERATIONS: dict[str, Operation] = {\n",
    ]
    for path, item in document["paths"].items():
        for method, operation in item.items():
            if not isinstance(operation, dict) or "operationId" not in operation:
                continue
            params = [resolve(p) for p in [*item.get("parameters", []), *operation.get("parameters", [])]]
            content = (operation.get("requestBody") or {}).get("content") or {}
            body = "none" if not content else "json" if "application/json" in content else "binary"
            statuses: list[int] = []
            response = "none"
            for status, answer in operation["responses"].items():
                if not re.fullmatch(r"[123]\d\d", str(status)):
                    continue
                statuses.append(int(status))
                if str(status) == "101" or operation.get("x-kyora-websocket"):
                    response = "websocket"
                    continue
                kinds = (answer.get("content") or {}) if "$ref" not in answer else {}
                if "application/json" in kinds:
                    response = "json" if response == "none" else response
                elif "application/x-ndjson" in kinds:
                    response = "ndjson"
                elif kinds and response == "none":
                    response = "binary"
            entry = {
                "method": method.upper(),
                "path": path,
                "tag": (operation.get("tags") or [""])[0],
                "path_params": tuple(p["name"] for p in params if p["in"] == "path"),
                "query": tuple(p["name"] for p in params if p["in"] == "query"),
                "idempotency_key": any(p["in"] == "header" and p["name"].lower() == "idempotency-key" for p in params),
                "body": body,
                "body_required": bool((operation.get("requestBody") or {}).get("required")),
                "content_types": tuple(content),
                "response": response,
                "statuses": tuple(sorted(statuses)),
            }
            lines.append(f"    {operation['operationId']!r}: {entry!r},\n")
    lines.append("}\n")
    return "".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail when the checked-in files are stale")
    args = parser.parse_args()
    outputs = {
        PACKAGE / "_models.py": models(SPEC),
        PACKAGE / "_error_codes.py": error_codes(SPEC),
        PACKAGE / "_operations.py": operations(SPEC),
    }
    stale = []
    for path, text in outputs.items():
        current = path.read_text() if path.exists() else ""
        if current == text:
            continue
        if args.check:
            stale.append(path)
            sys.stdout.writelines(
                difflib.unified_diff(current.splitlines(True), text.splitlines(True), str(path), "regenerated", n=1)
            )
        else:
            path.write_text(text)
    if stale:
        print(f"\nstale: {', '.join(p.name for p in stale)}; run `uv run scripts/generate.py`", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
